let currentLang = "ko";
try {
  currentLang = localStorage.getItem("gencore-lang") || "ko";
} catch (e) {
  console.warn("localStorage not available", e);
}

function applyLanguage(lang) {
  currentLang = lang;
  try {
    localStorage.setItem("gencore-lang", lang);
  } catch (e) {
    console.warn("localStorage not available", e);
  }
  const dict = TRANSLATIONS[lang];
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (dict[key]) el.innerHTML = dict[key];
  });
  // Update lang button label
  const btn = document.getElementById("langBtnLabel");
  if (btn) btn.textContent = LANG_LABELS[lang];
  // Mark active dropdown item
  document.querySelectorAll(".lang-dropdown button").forEach(b => {
    b.classList.toggle("active", b.dataset.lang === lang);
  });
  document.documentElement.lang = lang;

  // Re-render the active section to update its dynamic content
  const activeSection = document.querySelector(".content-section.active");
  if (activeSection && typeof renderSection === "function") {
    renderSection(activeSection.id);
  }
}
