const fs = require("fs");
const path = require("path");

const rootDir = path.resolve(__dirname, "..");
const outputPath = path.join(rootDir, "src", "data", "visible-i18n-auto.js");
const hangul = /[\uAC00-\uD7A3]/;
const voidTags = new Set(["img", "input", "br", "meta", "link", "hr", "source", "area", "base", "col", "embed", "param", "track", "wbr"]);

function loadAutoTranslations() {
  if (!fs.existsSync(outputPath)) return { en: {}, ja: {} };
  const match = fs.readFileSync(outputPath, "utf8").match(/window\.VISIBLE_I18N_AUTO\s*=\s*([\s\S]*?);\s*$/);
  if (!match) return { en: {}, ja: {} };
  try {
    const value = JSON.parse(match[1]);
    return { en: value.en || {}, ja: value.ja || {} };
  } catch {
    return { en: {}, ja: {} };
  }
}

function collectVisibleKorean(html) {
  const withoutCode = html.replace(/<(script|style)\b[^>]*>[\s\S]*?<\/\1>/gi, "");
  const stack = [];
  const values = new Set();

  for (const match of withoutCode.matchAll(/<[^>]*>|[^<]+/g)) {
    const token = match[0];
    if (token.startsWith("<!--")) continue;
    if (token.startsWith("</")) {
      stack.pop();
      continue;
    }
    if (token.startsWith("<")) {
      if (/^<!/.test(token)) continue;
      const tag = token.match(/^<([\w-]+)/)?.[1];
      for (const attribute of token.matchAll(/\b(?:placeholder|alt|title|aria-label|data-title)=("([^"]*)"|'([^']*)')/g)) {
        const value = attribute[2] || attribute[3] || "";
        if (hangul.test(value)) values.add(value);
      }
      if (tag && !voidTags.has(tag.toLowerCase()) && !/\/>$/.test(token)) {
        stack.push({ translated: /\bdata-i18n=/.test(token) });
      }
      continue;
    }
    const value = token.trim();
    if (value && hangul.test(value) && !stack.some(item => item.translated)) values.add(value);
  }
  return [...values];
}

async function translate(text, target) {
  const url = new URL("https://translate.googleapis.com/translate_a/single");
  url.searchParams.set("client", "gtx");
  url.searchParams.set("sl", "ko");
  url.searchParams.set("tl", target);
  url.searchParams.set("dt", "t");
  url.searchParams.set("q", text);
  const response = await fetch(url);
  if (!response.ok) throw new Error(`Translation request failed: ${response.status}`);
  const data = await response.json();
  return data[0].map(part => part[0] || "").join("");
}

async function syncLanguage(translations, sourceTexts, language) {
  const pending = sourceTexts.filter(text => !translations[language][text]);
  const queue = [...pending];
  const workerCount = 8;
  async function worker() {
    while (queue.length) {
      const source = queue.shift();
      translations[language][source] = await translate(source, language);
    }
  }
  await Promise.all(Array.from({ length: workerCount }, worker));
  return pending.length;
}

async function main() {
  const translations = loadAutoTranslations();
  const htmlPaths = fs.readdirSync(rootDir)
    .filter(name => name.toLowerCase().endsWith(".html"))
    .map(name => path.join(rootDir, name))
    .concat(
      fs.readdirSync(path.join(rootDir, "assets", "documents", "mai-install"))
        .filter(name => name.toLowerCase().endsWith(".html"))
        .map(name => path.join(rootDir, "assets", "documents", "mai-install", name))
    );
  const sourceTexts = [...new Set(htmlPaths.flatMap(htmlPath =>
    [...collectVisibleKorean(fs.readFileSync(htmlPath, "utf8"))]
  ))];
  const [englishAdded, japaneseAdded] = await Promise.all([
    syncLanguage(translations, sourceTexts, "en"),
    syncLanguage(translations, sourceTexts, "ja")
  ]);
  const output = `/* Generated by tools/sync-visible-i18n.js. Do not edit manually. */\nwindow.VISIBLE_I18N_AUTO = ${JSON.stringify(translations, null, 2)};\n`;
  fs.writeFileSync(outputPath, output, "utf8");
  console.log(`Visible translations synced: en +${englishAdded}, ja +${japaneseAdded}`);
}

main().catch(error => {
  console.error(error.message);
  process.exit(1);
});
